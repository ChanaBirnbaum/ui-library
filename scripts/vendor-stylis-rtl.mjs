#!/usr/bin/env node
// scripts/vendor-stylis-rtl.mjs
//
// Pre-bundles `stylis-plugin-rtl` (and its transitive deps: `stylis`,
// `cssjanus`) into a single, fully self-contained ESM file with zero
// remaining `import` statements, written to src/vendor/.
//
// Why this exists: our library build (vite.config.ts) uses Rollup's
// `output.preserveModules: true` to avoid circular-dependency TDZ bugs
// among our own src files. That setting also applies to any non-external
// node_modules dependency that ends up in the graph — Rollup then ships
// it as a *mirror* of its original package structure under
// dist/node_modules/..., wired together with relative imports and a
// Rollup-specific CJS/ESM interop helper. When a *different* bundler
// (webpack in a consuming host/MFE) re-processes those files, it applies
// its own interop on top and can double-wrap the default export, turning
// the RTL plugin function into a non-callable object at runtime
// ("X is not a function" inside IpsRtlProvider / IpsThemeProvider).
//
// Fix: resolve this dependency chain before Rollup ever sees it. esbuild
// bundles it into one flat file with no remaining imports, so downstream
// bundlers have nothing left to (mis)interpret — it becomes a plain
// function definition, same as any other first-party src file. Consumers
// need zero changes; nothing new to install.
//
// Re-run after bumping the `stylis-plugin-rtl` devDependency version:
//   node scripts/vendor-stylis-rtl.mjs

import { build } from 'esbuild'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const rootDir = path.resolve(__dirname, '..')
const outfile = path.resolve(rootDir, 'src/vendor/stylis-plugin-rtl.js')

const banner = `// Generated by scripts/vendor-stylis-rtl.mjs — do not edit by hand.
// Self-contained bundle of stylis-plugin-rtl (+ stylis, cssjanus): no
// remaining imports, safe to re-bundle by any downstream tool.
// Re-run: node scripts/vendor-stylis-rtl.mjs
`

await build({
  entryPoints: ['stylis-plugin-rtl'],
  bundle: true,
  platform: 'browser',
  mainFields: ['module', 'main'],
  format: 'esm',
  target: 'es2019',
  outfile,
  banner: { js: banner },
  legalComments: 'none',
  absWorkingDir: rootDir,
})

console.log(`vendored stylis-plugin-rtl -> ${path.relative(process.cwd(), outfile)}`)
